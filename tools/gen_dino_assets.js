// Usage (from the repo root): node tools/gen_dino_assets.js > firmware/src/face/face_assets.h
// Generates the dino fonts (big 9x13 digits, small 4x7, text 5x7) and the 16 menu/prop icons
// from the design's rig.js (art/reference/dino-v1/). Deterministic.
const path = require('path');
const R = require(path.join(__dirname, '..', 'art', 'reference', 'dino-v1', 'rig.js'));
const { BIG, SMALL, TXT, ICON } = R;
const ICON_ORDER = ['clock','alarm','focus','games','friends','chat','settings','back','meteor','bug','duel','pong','egg','mail','leaf','coffee'];
const out = [];
out.push('// GENERATED by tools/gen_dino_assets.js from art/reference/dino-v1/rig.js. Do not edit.');
out.push('#pragma once\n#include <stdint.h>\n\nnamespace face {\n');
out.push("struct Glyph { char ch; uint8_t w, h; const char* rows; };  // rows: w*h chars, '#' = lit; heart is '*'");
const emit = (name, font) => {
  const keys = Object.keys(font);
  out.push(`static const Glyph ${name}[] = {`);
  for (const k of keys) {
    const g = font[k]; const ch = k === '♥' ? '*' : k;
    const lit = ch === "'" ? "\\'" : ch === '\\' ? '\\\\' : ch;
    out.push(`  {'${lit}', ${g[0].length}, ${g.length}, "${g.join('')}"},`);
  }
  out.push('};');
  out.push(`static const int ${name}_N = ${keys.length};\n`);
};
emit('FONT_BIG', BIG); emit('FONT_SMALL', SMALL); emit('FONT_TXT', TXT);
out.push('enum class Icon : uint8_t { ' + ICON_ORDER.map(k => k[0].toUpperCase() + k.slice(1)).join(', ') + ' };');
out.push('static const uint8_t ICONS16[16][32] = {  // 16x16, row-major, MSB = left pixel');
for (const k of ICON_ORDER) {
  const a = ICON[k], bytes = [];
  for (let y = 0; y < 16; y++) for (let b = 0; b < 2; b++) { let v = 0; for (let x = 0; x < 8; x++) if (a[y * 16 + b * 8 + x]) v |= 0x80 >> x; bytes.push('0x' + v.toString(16).padStart(2, '0')); }
  out.push('  {' + bytes.join(',') + '},  // ' + k);
}
out.push('};\n}  // namespace face');
console.log(out.join('\n'));
