#!/usr/bin/env python3
"""Writes docs/guide-anims.js: the sheet's own frames (art/reference/dino-v1) for the clips the user
guide shows, bit-packed + base64, with each frame's hold time. Run from the repo root:
    python3 tools/gen_guide_anims.py
Deterministic: same reference in, same file out."""
import base64, json, os

REF = 'art/reference/dino-v1'
KEYS = ['idle', 'pet', 'overpet', 'rawr', 'shake', 'pickup', 'tilt', 'sleep', 'wake',
        'time', 'clock', 'menu', 'setalarm', 'alarm', 'snooze', 'dismiss',
        'focuspick', 'focus', 'focusdone', 'break', 'stopwatch']
W, H = 128, 64

timing = json.load(open(os.path.join(REF, 'dino_timing.json')))
bits = open(os.path.join(REF, 'dino_frames.bin'), 'rb').read()
out = {}
for c in timing['clips']:
    if c['key'] not in KEYS:
        continue
    frames = []
    for f in c['frames']:
        px = bits[f['index'] * W * H:(f['index'] + 1) * W * H]
        packed = bytearray(W * H // 8)
        for i, v in enumerate(px):
            if v:
                packed[i >> 3] |= 0x80 >> (i & 7)
        frames.append({'ms': f['ms'], 'note': f.get('note', ''), 'd': base64.b64encode(bytes(packed)).decode()})
    out[c['key']] = {'id': c['id'], 'name': c['name'], 'frames': frames}
missing = [k for k in KEYS if k not in out]
assert not missing, missing
with open('docs/guide-anims.js', 'w') as fh:
    fh.write('// Generated by tools/gen_guide_anims.py from art/reference/dino-v1. Do not edit.\n')
    fh.write('window.DINO_ANIMS=' + json.dumps(out, separators=(',', ':')) + ';\n')
print(sum(len(v['frames']) for v in out.values()), 'frames', os.path.getsize('docs/guide-anims.js') // 1024, 'KB')
